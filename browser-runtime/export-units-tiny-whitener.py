"""Export the units-tiny fixture session's neutral whitener (drowse's
``tests/support/browser_units.py::fixture``) in the browser's eigen form, so the
host `unitFind` port can replay drowse's unit-reads golden without Python.

Per layer the whitener is ``Σ = λI + XᵀX/N`` over the centred neutral rows ``X``;
the browser's ``SerializedMahalanobisWhitener`` holds ``λ`` (``ridge``), the
right-singular directions ``V`` (``basis`` rows) and ``s²/N`` (``eigenvalues``),
from which ``Σ^{-1/2} = (1/√λ)(I − V diag(g) Vᵀ)``, ``g = 1 − √(λ/(λ+s²/N))``
(native ``LayerWhitener._root_factors``).

Run from the drowse.ai root: PYTHONPATH=drowse python browser-runtime/export-units-tiny-whitener.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "drowse"))

from tests.support.browser_units import ARCHES, fixture, model_file_sha256  # noqa: E402

OUT = Path(__file__).resolve().parent / "fixtures" / "units-tiny-whitener-v1.json"


def export() -> dict:
    arches = {}
    for arch in ARCHES:
        with fixture(arch) as fx:
            whitener = fx.session.whitener
            assert whitener is not None
            layers = []
            for layer in sorted(int(L) for L in whitener.layer_means):
                X = whitener._X[layer].to(torch.float64)
                n = int(X.shape[0])
                lam = float(whitener._lambda[layer])
                evals, U = torch.linalg.eigh(X @ X.T)
                keep = evals > max(float(evals.max()), 0.0) * 1e-12
                s2 = evals[keep]
                V = (X.T @ U[:, keep]) / s2.sqrt()
                order = torch.argsort(s2, descending=True)
                layers.append({
                    "layer": layer,
                    "rows": n,
                    "ridge": lam,
                    "mean": [float(x) for x in whitener.layer_means[layer].double()],
                    "eigenvalues": [float(x) for x in (s2[order] / n)],
                    "basis": [[float(x) for x in V[:, i]] for i in order.tolist()],
                })
            arches[arch] = layers
    return {
        "schemaVersion": 1,
        "about": "The units-tiny fixture session's neutral whitener per layer in eigen form "
                 "(ridge λ, basis rows V, eigenvalues s²/N); generated by "
                 "browser-runtime/export-units-tiny-whitener.py from drowse's fixture.",
        "fixtureModels": {"name": "units-tiny-models-v1", "sha256": model_file_sha256()},
        "arches": arches,
    }


if __name__ == "__main__":
    OUT.write_text(json.dumps(export(), indent=1) + "\n")
    print(OUT)
